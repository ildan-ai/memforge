# memory-preamble-extract: extract the operator-curated preamble from
# an existing MEMORY.md into a _memforge.yaml config file (Phase 1
# migration helper companion).
#
# ADR: 0001 §Phase 1 T3 (closes the second BLOCKER from memory-index-gen
# tabletop: preamble loss when generator is run on a folder without
# _memforge.yaml)
#
# Algorithm:
#   - Read MEMORY.md.
#   - Title = first H1 line (`# <title>`); fallback "Memory Index".
#   - Preamble = everything between the H1 and the first bullet line
#     (`- [`) or the first H2 (`## `), whichever comes first.
#   - Write _memforge.yaml with title + preamble fields.
#   - Skip if _memforge.yaml already exists (operator-set).
#
# Modes:
#   --dry-run   Show what would be written; don't write.
#   --apply     Write _memforge.yaml.
#
# Defaults: per-cwd memory + ~/.claude/global-memory/.

from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path
from typing import Optional

from memforge.cli.index_gen import _FENCE_LINE, _fence_opener
from memforge._terminal import terminal_safe, visible
from memforge.discovery import (
    SymlinkWriteRefused,
    access_error,
    read_text_no_follow,
    write_text_inside,
)


H1_RE = re.compile(r"^#\s+(.+?)\s*$")
H2_RE = re.compile(r"^##\s+")
BULLET_RE = re.compile(r"^-\s+\[")
GENERATED_HEADER_RE = re.compile(r"^<!-- GENERATED BY memory-index-gen", re.IGNORECASE)


def _closes_fence(line: str, fence: str) -> bool:
    match = _FENCE_LINE.match(line)
    return bool(
        match
        and match.group(1)[0] == fence[0]
        and len(match.group(1)) >= len(fence)
        and not match.group(2).strip(" \t")
    )


def _unwrap_single_fence(lines: list[str]) -> list[str]:
    """The content of ``lines`` when they are one backtick fence from end to
    end (how memory-index-gen copies a preamble), else ``lines`` unchanged."""
    while lines and not lines[0].strip():
        lines = lines[1:]
    while lines and not lines[-1].strip():
        lines = lines[:-1]
    if len(lines) < 2 or lines[0] != "`" * len(lines[0]):
        return lines
    fence = _fence_opener(lines[0])
    if not fence or lines[0] != fence:
        return lines
    for n in range(1, len(lines) - 1):
        if _closes_fence(lines[n], fence):
            return lines
    if lines[-1] != fence:
        return lines
    return lines[1:-1]


def extract(memory_md: Path) -> Optional[dict]:
    """Returns {title, preamble} or None if MEMORY.md missing.

    Raises OSError or UnicodeDecodeError for a MEMORY.md that is there but
    cannot be read: reporting it as missing would hide the error.
    """
    if not os.path.exists(memory_md) and access_error(memory_md) is None:
        return None
    text = read_text_no_follow(memory_md)

    lines = text.splitlines()
    title = "Memory Index"
    preamble_lines: list[str] = []
    title_idx: Optional[int] = None
    for i, line in enumerate(lines):
        m = H1_RE.match(line)
        if m:
            title = m.group(1).strip()
            title_idx = i
            break
    start = (title_idx + 1) if title_idx is not None else 0
    fence = ""
    for i in range(start, len(lines)):
        line = lines[i]
        if fence:
            # Inside a fence nothing ends the preamble: the generator copies
            # it as literal text, so its lines are not MEMORY.md structure.
            if _closes_fence(line, fence):
                fence = ""
            preamble_lines.append(line)
            continue
        if BULLET_RE.match(line):
            break
        if H2_RE.match(line):
            break
        if GENERATED_HEADER_RE.match(line):
            break
        fence = _fence_opener(line) or ""
        preamble_lines.append(line)

    preamble_lines = _unwrap_single_fence(preamble_lines)
    preamble = "\n".join(preamble_lines).strip()
    return {"title": title, "preamble": preamble}


def render_yaml(cfg: dict) -> str:
    """Hand-render a minimal YAML for the _memforge.yaml config. Avoids
    a PyYAML dependency for the writer side."""
    out: list[str] = []
    # Escape backslash FIRST, then double-quote, for the double-quoted YAML
    # scalar. Escaping only the quote left a literal backslash (e.g. a Windows
    # path in the H1) producing an invalid/changed escape sequence that a real
    # downstream YAML parser would mis-read or reject (preamble-01).
    raw_title = cfg.get("title", "Memory Index")
    title = raw_title.replace("\\", "\\\\").replace('"', '\\"')
    out.append(f'title: "{title}"')
    preamble = cfg.get("preamble", "")
    if not preamble:
        out.append('preamble: ""')
    else:
        out.append("preamble: |")
        for line in preamble.splitlines():
            out.append(f"  {line}")
    return "\n".join(out) + "\n"


def cmd_run(folders: list[Path], apply: bool) -> int:
    rc = 0
    for folder in folders:
        err = access_error(folder)
        if err is not None:
            sys.stderr.write(f"error: cannot read {visible(folder)}: {visible(err)}\n")
            rc = 1
            continue
        if not os.path.exists(folder):
            sys.stderr.write(f"warning: skipping nonexistent {visible(folder)}\n")
            continue
        target_yaml = folder / "_memforge.yaml"
        memory_md = folder / "MEMORY.md"
        print(f"\n====== {visible(folder)} ======")
        if os.path.exists(target_yaml):
            print(f"  _memforge.yaml already exists; skipping")
            continue
        if os.path.islink(memory_md):
            sys.stderr.write(f"error: refusing to read through a symlink: {visible(memory_md)}\n")
            rc = 1
            continue
        try:
            cfg = extract(memory_md)
        except (OSError, UnicodeDecodeError) as exc:
            sys.stderr.write(f"error: cannot read {visible(memory_md)}: {visible(exc)}\n")
            rc = 1
            continue
        if cfg is None:
            print(f"  MEMORY.md missing; nothing to extract")
            continue
        rendered = render_yaml(cfg)
        print(f"  title: {visible(cfg['title'])}")
        if cfg["preamble"]:
            print(f"  preamble ({len(cfg['preamble'].splitlines())} lines):")
            for line in cfg["preamble"].splitlines()[:10]:
                print(f"    {visible(line)}")
            if len(cfg["preamble"].splitlines()) > 10:
                print(f"    ... +{len(cfg['preamble'].splitlines()) - 10} more lines")
        else:
            print("  (no preamble; only the H1 title)")
        if apply:
            try:
                write_text_inside(folder, target_yaml, rendered)
            except SymlinkWriteRefused as exc:
                sys.stderr.write(f"error: {visible(exc)}\n")
                rc = 1
                continue
            print(f"  WROTE {visible(target_yaml)}")
        else:
            print(f"  (dry-run; pass --apply to write {visible(target_yaml)})")
    return rc


def default_paths() -> list[Path]:
    """Default memory folders via the centralized, IDE/OS-neutral resolver
    (existence-filtered; one that cannot be looked at is kept, so it is
    reported)."""
    from memforge.paths import default_memory_paths

    return [p for p in default_memory_paths() if os.path.exists(p) or access_error(p)]


@terminal_safe
def main() -> int:
    p = argparse.ArgumentParser(
        prog="memory-preamble-extract",
        description="Extract MEMORY.md preamble into _memforge.yaml (Phase 1 migration helper).",
    )
    p.add_argument("--path", action="append", default=[], help="Folder (repeatable)")
    g = p.add_mutually_exclusive_group()
    g.add_argument("--dry-run", action="store_true")
    g.add_argument("--apply", action="store_true")
    args = p.parse_args()

    folders = [Path(x).resolve() for x in args.path] if args.path else default_paths()
    if not folders:
        sys.stderr.write("error: no folders specified and no defaults found\n")
        return 2

    if args.apply:
        print("=== APPLY MODE: _memforge.yaml will be written ===")
    else:
        print("=== DRY-RUN MODE: pass --apply to write ===")

    return cmd_run(folders, apply=args.apply)


if __name__ == "__main__":
    sys.exit(main())
