"""memory-index-gen treats `_memforge.yaml` as untrusted input.

The operator preamble is copied into MEMORY.md, the file agents load at
session start, so its type, size and content are bounded. A config the
generator cannot use is reported and the index is written without it.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from memforge.cli import index_gen

MEMORY = (
    "---\n"
    "name: one\n"
    "description: the only memory\n"
    "type: reference\n"
    "---\n\n"
    "Body.\n"
)

MARKER = index_gen.GENERATED_HEADER.splitlines()[0]


def _fenced(text: str, fence: str = "```") -> str:
    """The text as the generator copies it: literal, inside a fence."""
    return f"{fence}\n{text}\n{fence}"


@pytest.fixture
def folder(tmp_path: Path) -> Path:
    (tmp_path / "one.md").write_text(MEMORY, encoding="utf-8")
    return tmp_path


def _render(folder: Path, config: str, capsys) -> tuple[str, str]:
    """(generated index, stderr) for a folder holding the given config text."""
    (folder / "_memforge.yaml").write_text(config, encoding="utf-8")
    files = index_gen.discover_index_files(folder)
    output = index_gen.render(folder, files)
    return output, capsys.readouterr().err


def _assert_index_without_preamble(output: str, title: str = "Memory Index") -> None:
    assert output.startswith(f"# {title}\n\n\n{MARKER}\n")
    assert output.count(MARKER) == 1
    assert "- [one](one.md): the only memory" in output


def test_plain_preamble_is_kept(folder, capsys):
    output, err = _render(
        folder, "title: Team Index\npreamble: |\n  Line one.\n  \tIndented two.\n", capsys
    )

    assert output.startswith(f"# Team Index\n\n\n{_fenced(chr(10).join(['Line one.', chr(9) + 'Indented two.']))}\n\n{MARKER}\n")
    assert err == ""


def test_preamble_with_a_closed_comment_and_a_closed_fence_is_kept(folder, capsys):
    preamble = "<!-- note -->\n```\ncode\n```"
    config = "preamble: |\n" + "".join(f"  {line}\n" for line in preamble.splitlines())

    output, err = _render(folder, config, capsys)

    assert f"{_fenced(preamble, '````')}\n\n{MARKER}\n" in output
    assert err == ""


@pytest.mark.parametrize("config", [
    "- a\n- b\n",
    "just a scalar\n",
    "42\n",
])
def test_config_that_is_not_a_mapping_is_reported_and_ignored(folder, capsys, config):
    output, err = _render(folder, config, capsys)

    _assert_index_without_preamble(output)
    assert "_memforge.yaml" in err and "mapping" in err


@pytest.mark.parametrize("value", ["[a, b]", "{k: v}", "42", "true"])
def test_preamble_that_is_not_text_is_reported_and_dropped(folder, capsys, value):
    output, err = _render(folder, f"preamble: {value}\n", capsys)

    _assert_index_without_preamble(output)
    assert "preamble" in err and "text" in err


@pytest.mark.parametrize("value", ["[a, b]", "{k: v}", "42"])
def test_title_that_is_not_text_is_reported_and_defaulted(folder, capsys, value):
    output, err = _render(folder, f"title: {value}\npreamble: kept\n", capsys)

    assert output.startswith(f"# Memory Index\n\n\n{_fenced('kept')}\n\n{MARKER}\n")
    assert "title" in err and "text" in err


def test_multi_line_title_cannot_inject_lines(folder, capsys):
    output, err = _render(folder, 'title: "T\\n\\nInjected line"\n', capsys)

    _assert_index_without_preamble(output)
    assert "Injected line" not in output
    assert "title" in err


def test_preamble_over_the_cap_is_reported_and_dropped_whole(folder, capsys):
    over = "x" * (index_gen.PREAMBLE_MAX_BYTES + 1)

    output, err = _render(folder, f"preamble: {over}\n", capsys)

    _assert_index_without_preamble(output)
    assert "xxxx" not in output
    assert str(index_gen.PREAMBLE_MAX_BYTES) in err


def test_preamble_at_the_cap_is_kept(folder, capsys):
    at_cap = "x" * index_gen.PREAMBLE_MAX_BYTES

    output, err = _render(folder, f"preamble: {at_cap}\n", capsys)

    assert f"{_fenced(at_cap)}\n\n{MARKER}\n" in output
    assert err == ""


def test_control_characters_are_stripped_from_the_preamble(folder, capsys):
    config = 'preamble: "keep\\ttab\\nnext\\x1b[31m red\\x00\\x07\\x7f\\u0085\\r end"\n'

    output, _err = _render(folder, config, capsys)

    assert f"{_fenced(chr(10).join(['keep' + chr(9) + 'tab', 'next[31m red end']))}\n\n{MARKER}\n" in output


@pytest.mark.parametrize("preamble", [
    MARKER,
    "<!-- generated by MEMORY-INDEX-GEN (forged) -->",
    "# memforge:competing-claims:begin",
    "text\n# memforge:competing-claims:end",
])
def test_preamble_cannot_forge_a_generated_marker(folder, capsys, preamble):
    config = "preamble: |\n" + "".join(f"  {line}\n" for line in preamble.splitlines())

    output, err = _render(folder, config, capsys)

    _assert_index_without_preamble(output)
    assert "memforge:competing-claims" not in output
    assert "preamble" in err


@pytest.mark.parametrize("preamble", [
    "<!-- an unterminated comment swallows what follows",
    "```\nan unterminated fence swallows what follows",
    "~~~\nan unterminated fence swallows what follows",
    "<!-- closed --> but then <!-- open again",
    "```\na tilde line does not close a backtick fence\n~~~\nswallows",
    "~~~\na backtick line does not close a tilde fence\n```\nswallows",
    "````\na shorter fence does not close a longer one\n```\nswallows",
    "```\ntext after the fence characters means it is not a closing fence\n``` swallows",
    "```\nclosed\n```\n~~~\nreopened with the other character, swallows",
    "```\nbackticks\n```",
    "~~~\ntildes\n~~~",
    "```python\na longer closing fence closes\n`````",
    "intro\n   ```\nindented up to three spaces\n   ```   ",
    "intro\n    ```\nfour spaces is an indented code line, not a fence",
    "inline ``` backticks are not a fence",
])
def test_unbalanced_comments_and_fences_are_copied_as_literal_text(folder, capsys, preamble):
    # Nothing in the copy can swallow the generated marker: the copy's own
    # fence is longer than any backtick run in it.
    config = "preamble: |\n" + "".join(f"  {line}\n" for line in preamble.splitlines())

    output, err = _render(folder, config, capsys)

    longest = max(len(run) for run in __import__("re").findall(r"`+", preamble) or [""])
    fenced = _fenced(preamble.rstrip(), "`" * max(3, longest + 1))
    assert f"\n{fenced}\n\n{MARKER}\n" in output
    assert output.count(MARKER) == 1
    assert err == ""


def test_write_mode_still_writes_the_index_when_the_preamble_is_dropped(folder, capsys):
    (folder / "_memforge.yaml").write_text("preamble: [not, text]\n", encoding="utf-8")

    rc = index_gen.process(folder, "write")

    assert rc == 0
    _assert_index_without_preamble((folder / "MEMORY.md").read_text(encoding="utf-8"))
    assert "preamble" in capsys.readouterr().err
