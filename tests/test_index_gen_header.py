"""The generated MEMORY.md header line is a format contract.

`memory-index-gen --check` compares a checked-in MEMORY.md byte for byte with
fresh output, so any change to the header line turns every index written by an
earlier release into drift. The line is pinned as UTF-8 bytes; the dash in it
is U+2014.
"""

from __future__ import annotations

from pathlib import Path

from memforge.cli import index_gen

HEADER_LINE = (
    b"<!-- GENERATED BY memory-index-gen \xe2\x80\x94 "
    b"DO NOT EDIT THE BULLET LIST DIRECTLY. -->\n"
)


def _folder(tmp_path: Path) -> Path:
    (tmp_path / "one.md").write_text(
        "---\nname: one\ndescription: the only memory\ntype: reference\n---\n\nBody.\n",
        encoding="utf-8",
    )
    return tmp_path


def test_written_index_carries_the_header_line_unchanged(tmp_path: Path):
    folder = _folder(tmp_path)

    assert index_gen.process(folder, "write") == 0

    # The file is written with the platform's newline, as write_text writes it.
    written = (folder / "MEMORY.md").read_bytes().replace(b"\r\n", b"\n")
    assert HEADER_LINE in written


def test_an_index_with_the_header_line_passes_check(tmp_path: Path, capsys):
    folder = _folder(tmp_path)
    files = index_gen.discover_index_files(folder)
    body = index_gen.render(folder, files).encode("utf-8")
    start = body.index(b"<!-- GENERATED BY memory-index-gen")
    end = body.index(b"\n", start) + 1
    (folder / "MEMORY.md").write_bytes(body[:start] + HEADER_LINE + body[end:])

    assert index_gen.process(folder, "check") == 0
    assert capsys.readouterr().out.startswith("OK ")
